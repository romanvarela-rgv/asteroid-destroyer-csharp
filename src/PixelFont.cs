        // Mascara del texto (true = pixel lleno), con las 9 filas completas para que
        // todos los textos compartan la linea base. crop = true recorta tambien arriba y abajo.
        public static bool[,] TextMask(string text, bool crop = false)
        {
            int width = 0;
            foreach (char ch in text)
                width += Advance(ch);

            var line = new bool[Math.Max(width, 1), ROWS];
            int ox = 0;
            foreach (char ch in text)
            {
                KeyValuePair<int, string[]> g;
                if (glyphs.TryGetValue(ch, out g))
                {
                    string[] rows = g.Value;
                    for (int y = 0; y < rows.Length; y++)
                        for (int x = 0; x < rows[y].Length; x++)
                            if (rows[y][x] == '#')
                            {
                                line[ox + x, g.Key + y] = true;
                                line[ox + x + 1, g.Key + y] = true; // engrosado
                            }
                }
                ox += Advance(ch);
            }

            // Recorte horizontal (y vertical si se pide)
            int minX = int.MaxValue, minY = int.MaxValue, maxX = -1, maxY = -1;
            for (int y = 0; y < ROWS; y++)
                for (int x = 0; x < line.GetLength(0); x++)
                    if (line[x, y])
                    {
                        minX = Math.Min(minX, x); maxX = Math.Max(maxX, x);
                        minY = Math.Min(minY, y); maxY = Math.Max(maxY, y);
                    }

            if (maxX < 0) return new bool[1, ROWS]; // texto vacio
            if (!crop) { minY = 0; maxY = ROWS - 1; }

            var mask = new bool[maxX - minX + 1, maxY - minY + 1];
            for (int y = minY; y <= maxY; y++)
                for (int x = minX; x <= maxX; x++)
                    mask[x - minX, y - minY] = line[x, y];
            return mask;
        }

        // Ancho que ocupa cada caracter: la letra + 1 de engrosado + 1 de separacion
        private static int Advance(char ch)
        {
            KeyValuePair<int, string[]> g;
            if (ch != ' ' && glyphs.TryGetValue(ch, out g))
                return g.Value[0].Length + 2;
            return SPACE_WIDTH;
        }
    }
